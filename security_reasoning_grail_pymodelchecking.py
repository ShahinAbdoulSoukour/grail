def load_traj(path: str | Path):
    """
    Load one SWE-agent-style .traj JSON execution trace.
    """
    path = Path(path)
    if not path.exists():
        raise FileNotFoundError(f"Trajectory not found: {path}")
    with path.open("r", encoding="utf-8") as f:
        data = json.load(f)
    if not isinstance(data, dict):
        raise ValueError(".traj must contain a top-level JSON object")
    if not isinstance(data.get("trajectory"), list):
        raise ValueError(".traj must contain a top-level 'trajectory' list")
    return data


def get_trajectory(data):
    """
    Return only dictionary trajectory steps.
    """
    return [step for step in data["trajectory"] if isinstance(step, dict)]


