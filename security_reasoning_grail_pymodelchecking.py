def load_environment_snapshot(path: str | Path | None):
    """
    Load an optional environment snapshot for self-adaptation testing.

    Accepted shapes are either:
      {"S": {"A": [...], "T": [...], "M": [...], "C": [...]}}
    or directly:
      {"A": [...], "T": [...], "M": [...], "C": [...]}
    """
    if path is None:
        return None

    path = Path(path)
    if not path.exists():
        raise FileNotFoundError(f"Environment snapshot not found: {path}")

    with path.open("r", encoding="utf-8") as f:
        data = json.load(f)

    if not isinstance(data, dict):
        raise ValueError("Environment snapshot must contain a JSON object")

    if "S" in data and isinstance(data["S"], dict):
        return data

    return {"S": data}



def main() -> None:
    args = parse_args()

    if not args.traj_before or not args.kg:
        raise SystemExit("--traj-before and --kg are required unless --self-test is used")

    scenario = load_scenario_config(args.scenario_config)
    store = load_knowledge_graph(args.kg)
    leaf_goals = query_all_leaf_goals(store)
    print(f"Leaf goals found: {len(leaf_goals)}")

    model = load_embedding_model()
    cache_path = None if args.no_cache else embedding_cache_path(args.kg)
    _, leaf_goal_embeddings = build_leaf_goal_embeddings(
        model,
        leaf_goals,
        cache_path=cache_path,
    )
    print(f"Leaf-goal embedding matrix: {leaf_goal_embeddings.shape}")

    print("\n=== BEFORE: monitoring + goal reasoning ===")
    before = analyze_runtime_trace(
        traj_path=args.traj_before,
        kg_path=args.kg,
        model=model,
        store=store,
        leaf_goals=leaf_goals,
        leaf_goal_embeddings=leaf_goal_embeddings,
        scenario=scenario,
        top_k_goals=args.top_k_goals,
        operation_limit=args.operation_limit,
        operation_score_threshold=args.operation_score_threshold,
    )

    for record in before["runtime_goal_reasoning"]:
        print_goal_candidates(record)
    print_ltl_results(before["ltl_results"])
    print_traceability(before)

    # Generate the AFTER trace from the selected KG mitigations.
    if args.use_existing_after:
        if not args.traj_after:
            raise SystemExit("--use-existing-after requires --traj-after")
        after_path = Path(args.traj_after)
        security_decisions = []
    else:
        before_data = load_traj(args.traj_before)
        print("\n=== GRAIL: enforce + adapt ===")
        protected, security_decisions = generate_protected_trajectory(
            before=before_data,
            kg_reasoning=before["runtime_goal_reasoning"],
            requirements=before["formal_requirements"],
            model=model,
        )
        print_decisions(security_decisions)

        after_path = Path(
            args.traj_after
            or Path(args.traj_before).with_name(
                Path(args.traj_before).stem + "_protected.traj"
            )
        )
        with after_path.open("w", encoding="utf-8") as f:
            json.dump(protected, f, indent=2, ensure_ascii=False)
        print(f"\nAFTER trajectory written to: {after_path}")

    print("\n=== AFTER: re-monitor + re-evaluate ===")
    after = analyze_runtime_trace(
        traj_path=after_path,
        kg_path=args.kg,
        model=model,
        store=store,
        leaf_goals=leaf_goals,
        leaf_goal_embeddings=leaf_goal_embeddings,
        scenario=scenario,
        top_k_goals=args.top_k_goals,
        operation_limit=args.operation_limit,
        operation_score_threshold=args.operation_score_threshold,
        bound_requirements_override=before["formal_requirements"],
    )

    print_ltl_results(after["ltl_results"])
    print_traceability(after)

    environment_before = load_environment_snapshot(args.environment_before)
    environment_after = load_environment_snapshot(args.environment_after)

    adaptation_plan = build_self_adaptation_plan(
        decisions=security_decisions,
        before=before,
        after=after,
        scenario=scenario,
        adaptation_history_path=args.adaptation_history,
        environment_before=environment_before,
        environment_after=environment_after,
    )

    # Persist the adaptation assessment inside the generated AFTER trajectory as well as in the side-car history file.
    if not args.use_existing_after:
        with after_path.open("r", encoding="utf-8") as f:
            protected_with_plan = json.load(f)

        protected_with_plan.setdefault("grail_security_agent", {})[
            "self_adaptation"
        ] = adaptation_plan

        with after_path.open("w", encoding="utf-8") as f:
            json.dump(protected_with_plan, f, indent=2, ensure_ascii=False)

    print_self_adaptation(adaptation_plan)

    # Results are printed to the console; the adaptation history is the persistent cross-execution artifact.
    comparison = compare_before_after(before, after)

    print("\n=== BEFORE / AFTER ===")
    print(f"Violations before: {comparison['before_violation_count']}")
    print(f"Violations after : {comparison['after_violation_count']}")
    print(f"Security recovery success: {comparison['security_recovery_success']}")
    print(f"Self-adaptation triggered: {adaptation_plan['status'] == 'TRIGGERED'}")

if __name__ == "__main__":
    main()
