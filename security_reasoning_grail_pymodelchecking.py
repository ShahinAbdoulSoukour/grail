"""
GRAIL: Goal-driven runtime governance for agentic AI systems.

This script implements the runtime prototype described in the GRAIL approach.
It processes a SWE-agent execution trajectory (``.traj``), normalizes runtime events into security-relevant facts,
retrieves relevant governance goals and their operationalizations from a goal-model KB, and verifies
scenario-specific security requirements using LTL.

The runtime workflow is:
    .traj
      --> runtime signal / security facts
      --> relevant leaf-goal retrieval
      --> goal-to-operation lookup
      --> formal requirement verification
      --> action policy
      --> enforcement / mitigation
      --> protected .traj
      --> re-verification
      --> traceability and self-adaptation assessment

The action policy is deliberately simple and explicit:
    satisfied --> ALLOW
    violated  --> BLOCK
    unknown   --> ESCALATE

The script also implements the self-adaptation mechanism described in the GRAIL prototype.
It maintains a persistent history of requirement violations across executions and identifies adaptation triggers
such as repeated goal violations, declared goal conflicts, and changes in the runtime environment.
When a trigger is reached, the prototype generates an adaptation plan linking
the affected requirement to the corresponding goal and operationalization.
Structural changes to the goal model are treated as requiring human approval;
the prototype does not silently modify the persistent RDF goal model.

The current enforcement adapters are deployment-specific to the SWE-agent
path-traversal case study. The governance reasoning, formal verification,
goal traceability, and self-adaptation logic are kept separate from these
concrete enforcement mechanisms.

Inputs:
    --traj-before
        Input SWE-agent execution trajectory.
    --traj-after
        Output path for the protected trajectory generated by GRAIL.
    --kg
        Goal-model knowledge graph (Turtle / RDF-star).
    --kb-variant
        Governance KB variant used for goal retrieval and operationalization.
    --scenario-config
        Scenario-specific requirements and optional self-adaptation settings.
    --adaptation-history
        Persistent JSON file used to accumulate violation history across executions.
    --environment-before / --environment-after
        Optional snapshots of the agentic-system environment used to detect environmental changes for self-adaptation.

The prototype is evaluated on scenario-specific executions and should not be interpreted as a complete or
domain-independent security enforcement system.
Its purpose is to demonstrate the integration of governance intent, runtime evidence, formal security requirements,
operationalization, enforcement, traceability, and self-adaptation.
"""

