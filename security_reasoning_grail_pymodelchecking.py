# ----------- Utility functions -----------

def text(value):
    """
    Convert a value to printable text without throwing on nested JSON.
    """
    if value is None:
        return ""
    if isinstance(value, str):
        return value
    try:
        return json.dumps(value, ensure_ascii=False)
    except TypeError:
        return str(value)


def parse_json_object(value):
    """
    Parse a trajectory state field that may be a JSON string or dict.
    """
    if isinstance(value, dict):
        return value
    if isinstance(value, str):
        try:
            parsed = json.loads(value)
        except json.JSONDecodeError:
            return {}
        return parsed if isinstance(parsed, dict) else {}
    return {}


def rdf_term_value(term):
    """
    Return the lexical value of a PyOxigraph/RDFLib RDF term.
    """
    if term is None:
        return ""
    value = getattr(term, "value", None)
    if value is not None:
        return str(value)
    raw = str(term)
    if raw.startswith("<") and raw.endswith(">"):
        return raw[1:-1]
    return raw


def validate_iri(value, field_name: str = "IRI"):
    """
    Validate an absolute IRI before inserting it into SPARQL text.
    """
    value = str(value).strip()
    if not value:
        raise ValueError(f"{field_name} is empty")
    if value.startswith("<") or value.endswith(">"):
        raise ValueError(f"{field_name} must be a raw IRI: {value}")
    if any(ch in value for ch in ("<", ">", "\n", "\r", "\t")):
        raise ValueError(f"Invalid characters in {field_name}: {value}")
    if not re.match(r"^[A-Za-z][A-Za-z0-9+.-]*:", value):
        raise ValueError(f"Not an absolute IRI: {value}")
    return value


def local_name(uri) -> str:
    """
    Return the fragment/slash local name of an RDF resource.
    """
    value = str(uri)
    if "#" in value:
        return value.rsplit("#", 1)[-1]
    return value.rstrip("/").rsplit("/", 1)[-1]


