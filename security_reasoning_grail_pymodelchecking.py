def load_knowledge_graph(ttl_path: str | Path):
    """
    Load RDF/RDF-star with PyOxigraph, as required by the project KG.
    """
    try:
        from pyoxigraph import RdfFormat, Store
    except ImportError as exc:
        raise ImportError(
            "PyOxigraph is required for the runtime KG. Install with: "
            "pip install pyoxigraph"
        ) from exc

    path = Path(ttl_path)
    if not path.exists():
        raise FileNotFoundError(f"Knowledge graph not found: {path}")

    store = Store()
    store.load(path=str(path), format=RdfFormat.TURTLE)
    return store


def query_all_leaf_goals(store):
    """
    Retrieve leaf goals; embeddings use ONLY gm:goalName.
    """
    query = f"""
    PREFIX gm: <{GM}>
    SELECT DISTINCT ?goal ?standard ?goalId ?goalName ?classification ?functionName
    WHERE {{
        ?goal a gm:LeafGoal ;
              gm:goalId ?goalId ;
              gm:goalName ?goalName .
        OPTIONAL {{ ?goal gm:standardName ?standard . }}
        OPTIONAL {{ ?goal gm:classification ?classification . }}
        OPTIONAL {{ ?goal gm:functionName ?functionName . }}
    }}
    """

    goals = []
    for row in store.query(query):
        goals.append({
            "uri": rdf_term_value(row["goal"]),
            "standard": rdf_term_value(row["standard"]) or None,
            "goal_id": rdf_term_value(row["goalId"]),
            "goal_name": rdf_term_value(row["goalName"]).strip(),
            "classification": rdf_term_value(row["classification"]) or None,
            "function_name": rdf_term_value(row["functionName"]) or None,
        })

    unique = {goal["uri"]: goal for goal in goals}
    return sorted(unique.values(), key=lambda g: (
        g["standard"] or "", g["goal_id"], g["goal_name"]
    ))


def query_goal_by_uri(store, goal_uri):
    """
    Return one leaf goal by URI when a scenario explicitly supplies one.
    """
    goal_uri = validate_iri(goal_uri, "goal_uri")
    query = f"""
    PREFIX gm: <{GM}>
    SELECT ?goalId ?goalName ?standard
    WHERE {{
        BIND(<{goal_uri}> AS ?goal)
        ?goal a gm:LeafGoal ;
              gm:goalId ?goalId ;
              gm:goalName ?goalName .
        OPTIONAL {{ ?goal gm:standardName ?standard . }}
    }}
    LIMIT 1
    """
    rows = list(store.query(query))
    if not rows:
        return None
    row = rows[0]
    return {
        "uri": goal_uri,
        "goal_id": rdf_term_value(row["goalId"]),
        "goal_name": rdf_term_value(row["goalName"]),
        "standard": rdf_term_value(row["standard"]) or None,
    }


def query_operations_for_goal(store, goal_uri,
    score_threshold: float = DEFAULT_OPERATION_SCORE_THRESHOLD,
    operation_limit: int = DEFAULT_OPERATION_LIMIT):
    """
    Retrieve Goal -> Operation links and their RDF-star scores.
    """
    goal_uri = validate_iri(goal_uri, "goal_uri")
    query = f"""
    PREFIX gm: <{GM}>
    SELECT ?operation ?operationId ?operationName ?source ?description ?score
    WHERE {{
        BIND(<{goal_uri}> AS ?goal)
        ?goal gm:operationalizedBy ?operation .

        ?operation a gm:Operation ;
                   gm:operationId ?operationId ;
                   gm:operationName ?operationName ;
                   gm:source ?source .

        OPTIONAL {{ ?operation gm:description ?description . }}
        OPTIONAL {{
            << ?goal gm:operationalizedBy ?operation >>
                gm:similarityScore ?score .
        }}

        FILTER(!BOUND(?score) || ?score >= {float(score_threshold)})
    }}
    ORDER BY DESC(COALESCE(?score, 0))
    LIMIT {int(operation_limit)}
    """

    operations = []
    for row in store.query(query):
        operations.append({
            "uri": rdf_term_value(row["operation"]),
            "operation_id": rdf_term_value(row["operationId"]),
            "operation_name": rdf_term_value(row["operationName"]),
            "source": rdf_term_value(row["source"]),
            "description": rdf_term_value(row["description"]),
            "goal_operation_score": (
                float(rdf_term_value(row["score"]))
                if row["score"] is not None else None
            ),
        })
    return operations


def query_parent_goal(store, goal_uri):
    """
    Return one parent link for traceability.
    """
    goal_uri = validate_iri(goal_uri, "goal_uri")
    query = f"""
    PREFIX gm: <{GM}>
    SELECT ?goalId ?goalName ?parent ?parentId ?parentName
    WHERE {{
        BIND(<{goal_uri}> AS ?goal)
        ?goal gm:goalId ?goalId ;
              gm:goalName ?goalName .
        OPTIONAL {{
            ?goal gm:parentGoal ?parent .
            ?parent gm:goalId ?parentId ;
                    gm:goalName ?parentName .
        }}
    }}
    LIMIT 1
    """
    rows = list(store.query(query))
    if not rows:
        return None
    row = rows[0]
    return {
        "uri": goal_uri,
        "goal_id": rdf_term_value(row["goalId"]),
        "goal_name": rdf_term_value(row["goalName"]),
        "parent_uri": rdf_term_value(row["parent"]) or None,
        "parent_id": rdf_term_value(row["parentId"]) or None,
        "parent_name": rdf_term_value(row["parentName"]) or None,
    }


def trace_goal_to_root(store, goal_uri, max_depth: int = 20):
    """
    Follow parentGoal links from leaf to root.
    """
    trace: list[dict[str, Any]] = []
    current = goal_uri
    visited: set[str] = set()

    for _ in range(max_depth):
        if not current or current in visited:
            break
        visited.add(current)
        node = query_parent_goal(store, current)
        if node is None:
            break
        trace.append(node)
        current = node["parent_uri"]
    return trace


# 5) ----------- Leaf-goal embeddings -----------

def load_embedding_model():
    """
    Load the same embedding model used in the operationalization work.
    """
    try:
        from sentence_transformers import SentenceTransformer
    except ImportError as exc:
        raise ImportError(
            "sentence-transformers is required. Install with: "
            "pip install sentence-transformers"
        ) from exc
    return SentenceTransformer(MODEL_NAME)


def embedding_cache_path(kg_path: str | Path):
    """
    Return a KG/version/model-specific local embedding cache file.
    """
    path = Path(kg_path)
    stat = path.stat()
    key = hashlib.sha256(
        f"{path.resolve()}|{stat.st_mtime_ns}|{stat.st_size}|{MODEL_NAME}".encode()
    ).hexdigest()[:16]
    return path.with_name(f".leaf_goal_embeddings_{key}.npz")


def build_leaf_goal_embeddings(model, leaf_goals, cache_path: str | Path | None = None):
    """
    Embed ONLY gm:goalName, as agreed for goal retrieval.
    """
    if not leaf_goals:
        raise ValueError("No LeafGoal nodes found in the KG")

    texts = [g["goal_name"].strip() for g in leaf_goals]
    if any(not value for value in texts):
        raise ValueError("A leaf goal has an empty goalName")

    if cache_path is not None:
        cache_path = Path(cache_path)
        if cache_path.exists():
            cached = np.load(cache_path, allow_pickle=True)
            if (
                str(cached["model"].tolist()) == MODEL_NAME
                and cached["uris"].tolist() == [g["uri"] for g in leaf_goals]
            ):
                return leaf_goals, np.asarray(cached["embeddings"], dtype=np.float32)

    embeddings = model.encode(
        texts,
        normalize_embeddings=True,
        convert_to_numpy=True,
        show_progress_bar=True,
    ).astype(np.float32)

    if cache_path is not None:
        np.savez_compressed(
            cache_path,
            model=np.array(MODEL_NAME),
            uris=np.array([g["uri"] for g in leaf_goals], dtype=str),
            embeddings=embeddings,
        )

    return leaf_goals, embeddings


def embed_text(model, value):
    """
    Embed one text with L2 normalization.
    """
    return np.asarray(
        model.encode([value], normalize_embeddings=True, convert_to_numpy=True)[0],
        dtype=np.float32,
    )


def retrieve_leaf_goals(model, leaf_goals, leaf_goal_embeddings, runtime_fact, top_k: int = DEFAULT_TOP_K_GOALS):
    """
    Runtime fact -> leaf goal retrieval.

    Because both vectors are normalized, the dot product equals cosine similarity.
    """
    if not runtime_fact.strip():
        return []

    fact_embedding = embed_text(model, runtime_fact)
    scores = leaf_goal_embeddings @ fact_embedding
    top_k = max(1, min(top_k, len(scores)))
    indices = np.argpartition(-scores, top_k - 1)[:top_k]
    indices = indices[np.argsort(-scores[indices])]

    result = []
    for rank, idx in enumerate(indices, start=1):
        goal = dict(leaf_goals[int(idx)])
        goal["retrieval_rank"] = rank
        goal["fact_goal_similarity"] = float(scores[int(idx)])
        goal["embedding_text"] = goal["goal_name"]
        result.append(goal)
    return result


def build_runtime_fact(step):
    """
    Turn one normalized signal into semantic text for goal retrieval.
    """
    event_type = step.get("event_type") or "runtime event"
    action = step.get("action") or ""
    observation = step.get("observation") or ""
    response = step.get("response") or ""
    thought = step.get("thought") or ""
    state = step.get("state") or {}
    facts = step.get("facts") or {}

    parts = [f"Runtime event: {event_type.replace('_', ' ')}."]
    if action:
        parts.append(f"Action: {action}.")
    if observation:
        parts.append(f"Observation: {observation}.")
    if response:
        parts.append(f"Agent response: {response}.")
    if thought:
        parts.append(f"Agent reasoning: {thought}.")

    true_facts = [k for k, v in facts.items() if v is True]
    if true_facts:
        parts.append("Security facts: " + ", ".join(true_facts) + ".")

    selected_context = {
        key: state[key]
        for key in (
            "service", "requested_path", "remote_access",
            "authentication", "authenticated", "tool",
        )
        if key in state
    }
    if selected_context:
        parts.append(
            "Runtime context: " + json.dumps(selected_context, ensure_ascii=False) + "."
        )

    return " ".join(parts)


# 6) ----------- Formal requirements + LTL verification (pyModelChecking) -----------

def normalize_ltl_for_pymodelchecking(formula_text):
    """
    Convert the scenario LTL syntax to a valid pyModelChecking formula.

    pyModelChecking represents an LTL specification as a universally quantified path formula A(...).
    The scenario files therefore stay simple and human-readable (G(...), F(...), U(...), ->, !), while this function
    performs only the syntax bridge needed by the model checker.
    """
    formula = str(formula_text).strip()
    if not formula:
        raise ValueError("LTL formula is empty")

    # Human-readable boolean syntax -> pyModelChecking syntax.
    formula = formula.replace("&&", " and ")
    formula = formula.replace("||", " or ")
    formula = formula.replace("->", "-->")
    formula = re.sub(r"!(?!=)", "not ", formula)

    # pyModelChecking's LTL grammar represents LTL specifications as
    # universally quantified state formulas A(path_formula).
    # Do not double-wrap formulas that are already quantified.
    compact = formula.lstrip()
    if re.match(r"^A\s*\(", compact) or re.match(r"^A\s+[A-Za-z]", compact):
        return formula

    return f"A({formula})"


def build_kripke_from_trace(steps):
    """
    Build the deterministic infinite Kripke extension of one .traj.
    The finite trajectory becomes:

        s0 -> s1 -> ... -> sn
                              ↘
                                sn

    The final self-loop is required because LTL is defined over infinite computations.
    pyModelChecking explicitly requires every Kripke state to have a successor.
    """
    try:
        from pyModelChecking import Kripke
    except ImportError as exc:
        raise ImportError(
            "pyModelChecking is required for formal verification. "
            "Install with: pip install pyModelChecking"
        ) from exc

    if not steps:
        return None, []

    states = list(range(len(steps)))
    transitions = [(i, i + 1) for i in range(len(states) - 1)]
    transitions.append((states[-1], states[-1]))

    # Keep labels as plain proposition names because the LTL parser also creates
    # atomic propositions from these exact names.
    labels = {
        i: {
            fact_name
            for fact_name, value in step.get("facts", {}).items()
            if value is True
        }
        for i, step in enumerate(steps)
    }

    kripke = Kripke(
        S=states,
        S0=[states[0]],
        R=transitions,
        L=labels,
    )
    return kripke, states


def requirement_violation_trigger_states(steps, requirement, violating_states):
    """
    Map semantic LTL violation states to concrete event states.
    """
    event_types = set(requirement.get("event_types", []))
    if not event_types:
        return list(violating_states)
    return [
        i
        for i in violating_states
        if 0 <= i < len(steps)
        and steps[i].get("event_type") in event_types
    ]



def _trace_labels(steps):
    """
    Normalize runtime facts into proposition-label sets.
    """
    labels = []
    for step in steps:
        facts = step.get("facts", {})
        if isinstance(facts, dict):
            labels.append({k for k, v in facts.items() if v is True})
        elif isinstance(facts, (list, tuple, set)):
            labels.append({str(k) for k in facts})
        else:
            labels.append(set())
    return labels


def _trace_formula_kind(formula_text):
    """
    Recognize the small LTL fragment used by the current scenario.
    """
    f = re.sub(r"\s+", " ", str(formula_text).strip())
    patterns = [
        ("G_NOT", re.compile(r"^G\(\s*(\w+)\s*->\s*!\s*(\w+)\s*\)$")),
        ("G_POS", re.compile(r"^G\(\s*(\w+)\s*->\s*(\w+)\s*\)$")),
        ("G_F", re.compile(r"^G\(\s*(\w+)\s*->\s*F\(\s*(\w+)\s*\)\s*\)$")),
        ("G_UNTIL", re.compile(r"^G\(\s*(\w+)\s*->\s*\(\s*!\s*(\w+)\s+U\s+(\w+)\s*\)\s*\)$")),
    ]
    for kind, rx in patterns:
        m = rx.match(f)
        if m:
            return kind, m.groups()
    return None, None


def direct_trace_ltl_status(steps, formula_text):
    """
    Evaluate the scenario's LTL fragment directly on one deterministic trace.

    This is the authoritative runtime verdict for a .traj: one observed execution
    with final-state stuttering. pyModelChecking remains a formal cross-check,
    but a library-specific state-set quirk must not change the runtime decision.
    """
    labels = _trace_labels(steps)
    n = len(labels)
    kind, args = _trace_formula_kind(formula_text)
    if kind is None:
        raise ValueError(f"Unsupported LTL fragment for deterministic trace evaluation: {formula_text}")

    def suffix_holds(start: int) -> bool:
        for k in range(start, n):
            if kind == "G_NOT":
                p, q = args
                if p in labels[k] and q in labels[k]:
                    return False
            elif kind == "G_POS":
                p, q = args
                if p in labels[k] and q not in labels[k]:
                    return False
            elif kind == "G_F":
                p, q = args
                if p not in labels[k]:
                    continue
                # F(q): q must hold at some state j >= k. The final state
                # stutters forever, so existence in the finite suffix is enough.
                if not any(q in labels[j] for j in range(k, n)):
                    return False
            elif kind == "G_UNTIL":
                p, q, r = args
                if p not in labels[k]:
                    continue
                witness = None
                for j in range(k, n):
                    if r in labels[j] and all(q not in labels[m] for m in range(k, j)):
                        witness = j
                        break
                if witness is None:
                    return False
        return True

    satisfying_states = [i for i in range(n) if suffix_holds(i)]
    status = "SATISFIED" if 0 in satisfying_states else "VIOLATED"
    violating_states = [i for i in range(n) if i not in satisfying_states]
    return status, satisfying_states, f"direct deterministic-trace semantics for {kind}"


def check_ltl(steps, requirements):
    """
    Verify requirements on the observed .traj and cross-check with pyModelChecking.
    """
    if not steps:
        return []

    try:
        import pyModelChecking
        from pyModelChecking.CTLS import modelcheck
        pymc_version = getattr(pyModelChecking, "__version__", "unknown")
    except ImportError as exc:
        raise ImportError(
            "pyModelChecking is required for formal verification. "
            "Install with: pip install pyModelChecking"
        ) from exc

    kripke, states = build_kripke_from_trace(steps)
    if kripke is None:
        return []

    results = []
    for requirement in requirements:
        event_types = set(requirement.get("event_types", []))
        applicable = any(step.get("event_type") in event_types for step in steps)

        if not applicable:
            results.append({
                **requirement,
                "status": "NOT_TRIGGERED",
                "satisfying_states": [],
                "violating_states": [],
                "violation_trigger_states": [],
                "model_checker": "pyModelChecking.CTLS + direct trace semantics",
                "pyModelChecking_version": pymc_version,
                "pyModelChecking_status": "NOT_TRIGGERED",
                "trace_semantics_status": "NOT_TRIGGERED",
                "verification_mismatch": False,
            })
            continue

        pymc_formula = normalize_ltl_for_pymodelchecking(requirement["formula"])
        try:
            pymc_satisfying = sorted(set(modelcheck(kripke, pymc_formula)))
            pymc_status = "SATISFIED" if states[0] in pymc_satisfying else "VIOLATED"
            pymc_violating = [s for s in states if s not in pymc_satisfying]
            pymc_error = None
        except Exception as exc:
            pymc_satisfying = []
            pymc_status = "ERROR"
            pymc_violating = []
            pymc_error = f"{type(exc).__name__}: {exc}"

        trace_status, trace_satisfying, semantics_note = direct_trace_ltl_status(
            steps, requirement["formula"]
        )
        trace_violating = [s for s in states if s not in trace_satisfying]
        trigger_states = requirement_violation_trigger_states(
            steps, requirement, trace_violating
        )

        results.append({
            **requirement,
            "status": trace_status,
            "satisfying_states": trace_satisfying,
            "violating_states": trace_violating,
            "violation_trigger_states": trigger_states,
            "pyModelChecking_formula": pymc_formula,
            "model_checker": "pyModelChecking.CTLS + direct trace semantics",
            "pyModelChecking_version": pymc_version,
            "pyModelChecking_status": pymc_status,
            "pyModelChecking_satisfying_states": pymc_satisfying,
            "pyModelChecking_violating_states": pymc_violating,
            "pyModelChecking_error": pymc_error,
            "trace_semantics_status": trace_status,
            "verification_mismatch": pymc_status not in {"ERROR", trace_status},
            "semantics": semantics_note + "; final-state stuttering",
        })

    return results


def bind_requirements_to_goals(requirements, step_goal_reasoning):
    """
    Bind each formal requirement to the most relevant leaf goal observed for that requirement's event types.

    This is the runtime instantiation step:
        interaction signal -> relevant leaf goal -> formal property.

    The paper's goal model remains the source of truth for traceability; the embedding score is only used to retrieve the relevant leaf goal.
    """
    bound = []
    for requirement in requirements:
        event_types = set(requirement.get("event_types", []))
        candidates = [
            record
            for record in step_goal_reasoning
            if record.get("event_type") in event_types
            and record.get("selected_leaf_goal") is not None
        ]
        best_goal = None
        if candidates:
            best_goal = max(
                (record["selected_leaf_goal"] for record in candidates),
                key=lambda g: g.get("fact_goal_similarity", -1.0),
            )

        item = dict(requirement)
        item["goal"] = best_goal
        bound.append(item)
    return bound


def goal_satisfaction_states(requirements, ltl_results):
    """
    Compute {satisfied, violated, unknown} for leaf goals.

    A goal is violated if one of its bound requirements is violated.
    It is satisfied when at least one bound requirement exists and none is violated.
    A goal with no evaluable requirement is unknown.
    """
    grouped: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for req, result in zip(requirements, ltl_results):
        goal = req.get("goal")
        if isinstance(goal, dict):
            grouped[goal["uri"]].append(result)

    states: dict[str, str] = {}
    for goal_uri, results in grouped.items():
        if any(r["status"] == "VIOLATED" for r in results):
            states[goal_uri] = "violated"
        elif any(r["status"] == "SATISFIED" for r in results):
            states[goal_uri] = "satisfied"
        else:
            states[goal_uri] = "unknown"
    return states


def action_policy(status):
    """
    Paper Section 5.4 policy:
        satisfied -> allow
        violated  -> block
        unknown   -> escalate
    """
    return {
        "satisfied": "ALLOW",
        "violated": "BLOCK",
        "unknown": "ESCALATE",
    }.get(status, "ESCALATE")


# 7) ----------- Runtime goal reasoning + mitigation selection -----------

def operation_runtime_applicability(model, runtime_fact, operation) -> float | None:
    """
    Optional semantic tie-breaker: runtime fact <-> operation text.
    """
    if model is None:
        return None
    op_text = " ".join(filter(None, [
        operation.get("operation_name", ""),
        operation.get("description", ""),
    ]))
    if not op_text.strip():
        return None
    fact = embed_text(model, runtime_fact)
    op = embed_text(model, op_text)
    return float(fact @ op)


def operation_compatible_with_event(operation, event_type: str | None):
    """
    Return whether a KG operation is a plausible adapter for this event type.

    This is a small deployment-level applicability filter.
    It prevents an operation such as "Trusted Library" from being applied to a path-traversal event just because it has a high goal->operation score.
    """
    if not event_type:
        return True

    adapter = infer_enforcement_adapter(operation)
    compatibility = {
        "path_traversal": {"path_or_access_control", "authentication_gate"},
        "install_dependency": {"dependency_allowlist"},
        "execute_command": {"command_allowlist"},
    }
    allowed = compatibility.get(event_type)
    if allowed is None:
        return True
    return adapter in allowed


def select_mitigation(model, operations, runtime_fact, event_type: str | None = None):
    """
    Select the highest-scoring event-compatible KG operation.

    Duplicate operation IDs can occur in the merged KG because an operation may be represented by more than one label/description.
    Collapse those duplicates before scoring so the same technical mitigation is considered only once.
    """
    if not operations:
        return None

    unique_operations: dict[str, dict[str, Any]] = {}
    for operation in operations:
        op_id = operation.get("operation_id") or operation.get("operation_name")
        if not op_id:
            continue
        previous = unique_operations.get(op_id)
        if previous is None or float(operation.get("goal_operation_score") or -1.0) > float(
            previous.get("goal_operation_score") or -1.0
        ):
            unique_operations[op_id] = dict(operation)

    compatible = [
        operation for operation in unique_operations.values()
        if operation_compatible_with_event(operation, event_type)
    ]

    # Never silently apply an arbitrary KG operation through the generic block adapter.
    # If nothing is compatible, return None and let the policy escalate.
    if not compatible:
        return None

    candidates = []
    for operation in compatible:
        item = dict(operation)
        item["enforcement_adapter"] = infer_enforcement_adapter(operation)
        item["runtime_operation_similarity"] = operation_runtime_applicability(
            model, runtime_fact, operation
        )
        goal_score = item.get("goal_operation_score")
        runtime_score = item.get("runtime_operation_similarity")
        item["selection_score"] = (
            float(goal_score)
            if goal_score is not None
            else (float(runtime_score) if runtime_score is not None else -1.0)
        )
        candidates.append(item)

    candidates.sort(
        key=lambda x: (
            x["selection_score"],
            x.get("runtime_operation_similarity") or -1.0,
        ),
        reverse=True,
    )

    selected = candidates[0]
    selected["compatible_candidate_count"] = len(compatible)
    selected["rejected_operation_ids"] = [
        op.get("operation_id")
        for op in operations
        if op.get("operation_id") not in {c.get("operation_id") for c in compatible}
    ]
    return selected


def analyze_step_against_kg(
    model,
    store,
    leaf_goals,
    leaf_goal_embeddings,
    step,
    top_k_goals,
    operation_limit,
    operation_score_threshold,
):
    """
    Retrieve relevant leaf goals and their KG mitigations for one signal.
    """
    runtime_fact = build_runtime_fact(step)
    candidates = retrieve_leaf_goals(
        model,
        leaf_goals,
        leaf_goal_embeddings,
        runtime_fact,
        top_k=top_k_goals,
    )

    for goal in candidates:
        goal["operations"] = query_operations_for_goal(
            store,
            goal["uri"],
            score_threshold=operation_score_threshold,
            operation_limit=operation_limit,
        )
        goal["hierarchy_leaf_to_root"] = trace_goal_to_root(store, goal["uri"])

    # The top embedding match is not necessarily the goal that exposes a
    # concrete enforcement operation for this runtime event. Therefore:
    #   1. retrieve the top-K goals by runtime-fact similarity;
    #   2. inspect their operationalizations;
    #   3. prefer the highest-ranked goal that has at least one
    #      event-compatible enforcement operation.
    #
    # This prevents a generic goal such as "Evaluate AI system security and
    # resilience" from blocking a more actionable access-control goal that
    # appears slightly lower in the retrieval list.
    selected_goal = candidates[0] if candidates else None
    selected_mitigation = None

    for goal in candidates:
        mitigation = select_mitigation(
            model,
            goal.get("operations", []),
            runtime_fact,
            event_type=step.get("event_type"),
        )
        if mitigation is not None:
            selected_goal = goal
            selected_mitigation = mitigation
            break

    return {
        "step": step["step"],
        "event_type": step.get("event_type"),
        "runtime_fact": runtime_fact,
        "goal_candidates": candidates,
        "selected_leaf_goal": selected_goal,
        "selected_mitigation": selected_mitigation,
        "selection_basis": (
            "highest runtime-fact retrieval rank with an "
            "event-compatible enforcement operation"
            if selected_mitigation is not None
            else "highest runtime-fact retrieval similarity"
        ),
    }


# 8) ----------- Mitigation risk + enforcement adapters -----------

def mitigation_risk(operation: dict[str, Any]) -> dict[str, Any]:
    """
    Interpret optional risk metadata from the KG.

    The current merged KG does not contain CWSS/CWE metadata for every
    operation, so absence is reported as 'unknown' rather than fabricated.
    A deployment may extend the KG with gm:cwssScore / gm:cweId / approval
    metadata without changing this interface.
    """
    cwss = operation.get("cwss")
    if cwss is not None:
        cwss = float(cwss)
        level = "low" if cwss < 4 else "medium" if cwss < 7 else "high"
        return {
            "cwss": cwss,
            "risk_level": level,
            "requires_human": level == "high",
        }
    return {
        "cwss": None,
        "risk_level": "unknown",
        "requires_human": False,
    }


def infer_enforcement_adapter(operation):
    """
    Map a KG operation to a concrete SWE-agent case-study adapter.
    """
    name = f"{operation.get('operation_name', '')} {operation.get('description', '')}".lower()

    # File/network access mediation techniques are suitable for the path-
    # traversal case even when their description does not literally contain
    # the words "access control".
    if any(k in name for k in (
        "path validation", "canonical", "file access mediation",
        "remote file access mediation", "network resource access mediation",
        "network access mediation", "local file permissions",
        "user account permissions", "user group permissions",
        "permissions control", "access control", "access mediation",
        "data access control", "downstream authorization",
    )):
        return "path_or_access_control"

    if "authentication" in name or "multi-factor" in name:
        return "authentication_gate"

    if any(k in name for k in (
        "trusted library", "software allowlist", "package allowlist",
        "dependency",
    )):
        return "dependency_allowlist"

    if any(k in name for k in (
        "allowlisted", "script allowlist", "command allowlist",
        "authorized script",
    )):
        return "command_allowlist"

    return "generic_block"


def apply_enforcement_adapter(raw_step, operation: dict[str, Any] | None):
    """
    Apply the selected mitigation to one SWE-agent trajectory step.

    This is the deployment-specific part of the prototype.
    GRAIL's generic action policy is independent of these mechanics.

    Example:
        operation = "Path Validation"
        -> state.path_validation = True
        -> state.file_access_granted = False
        -> observation = HTTP 403
    """
    patched = json.loads(json.dumps(raw_step))
    state = parse_json_object(patched.get("state"))

    if operation is None:
        state["action_blocked"] = True
        state["mitigation_active"] = False
        patched["state"] = json.dumps(state, ensure_ascii=False)
        patched["security_action"] = "escalate"
        return patched, {
            "adapter": None,
            "applied": False,
            "requires_human": True,
            "reason": "No KG mitigation candidate was available.",
        }

    adapter = infer_enforcement_adapter(operation)
    risk = mitigation_risk(operation)

    if adapter in {"path_or_access_control", "authentication_gate"}:
        if adapter == "path_or_access_control":
            # Path/access mediation must not fabricate successful authentication.
            # It only constrains the requested resource.
            state["path_validation"] = True
        else:
            state["authentication"] = True

        state["file_access_granted"] = False
        state["sensitive_data_exposed"] = False
        state["mitigation_active"] = True
        state["action_blocked"] = True
        patched["original_observation"] = patched.get("observation")
        patched["observation"] = BLOCKED_HTTP_OBSERVATION

    elif adapter == "dependency_allowlist":
        state["dependency_allowlist"] = True
        state["dependency_vulnerable"] = False
        state["untrusted_source"] = False
        state["mitigation_active"] = True
        state["action_blocked"] = True
        patched["original_observation"] = patched.get("observation")
        patched["observation"] = BLOCKED_INSTALL_OBSERVATION
        risk["requires_human"] = True

    elif adapter == "command_allowlist":
        state["command_allowlist"] = True
        state["command_executed"] = False
        state["mitigation_active"] = True
        state["action_blocked"] = True
        patched["original_observation"] = patched.get("observation")
        patched["observation"] = BLOCKED_COMMAND_OBSERVATION
        risk["requires_human"] = True

    else:
        # Generic enforcement means the security agent blocks the action, but
        # cannot safely claim that the concrete mitigation has been installed.
        state["action_blocked"] = True
        patched["original_observation"] = patched.get("observation")
        patched["observation"] = "[GRAIL] action blocked; mitigation adapter unavailable"
        risk["requires_human"] = True

    patched["state"] = json.dumps(state, ensure_ascii=False)
    patched["security_action"] = {
        "adapter": adapter,
        "operation_id": operation.get("operation_id"),
        "operation_name": operation.get("operation_name"),
    }

    return patched, {
        "adapter": adapter,
        "applied": adapter != "generic_block",
        "requires_human": bool(risk.get("requires_human")),
        "risk": risk,
    }


# 9. ----------- GRAIL action-policy loop: Monitor -> Evaluate -> Enforce -> Adapt -> Trace -----------

def apply_policy_patch(raw_step, patch):
    """
    Apply persistent runtime constraints already adopted by GRAIL.
    """
    step = json.loads(json.dumps(raw_step))
    state = parse_json_object(step.get("state"))
    state.update(patch)
    step["state"] = json.dumps(state, ensure_ascii=False)
    return step


def requirement_violations_at(raw_steps, requirements, index):
    """
    Return requirement IDs violated at one step of the current prefix.
    """
    steps = normalize_runtime_trace({"trajectory": raw_steps})
    results = check_ltl(steps, requirements)
    return [
        r["id"]
        for r in results
        if r["status"] == "VIOLATED" and index in r["violating_states"]
    ]


def requirement_goal_map(requirements):
    return {
        req["id"]: req["goal"]
        for req in requirements
        if isinstance(req.get("goal"), dict)
    }


def build_step_requirement_records(requirements, ltl_results,):
    return {
        result["id"]: {
            "status": result["status"],
            "goal": next(
                (req.get("goal") for req in requirements if req["id"] == result["id"]),
                None,
            ),
        }
        for result in ltl_results
    }


def generate_protected_trajectory(before, kg_reasoning, requirements, model=None):
    """
    Replay the BEFORE trace through the GRAIL action-policy loop.
    Important:
      - BLOCK is the governance decision from pi_g.
      - The selected mitigation comes from the KG operation attached to the
        violated goal.
      - The enforcement adapter changes the concrete SWE-agent state.
      - The patched step is re-verified before it is persisted.
    """
    after = json.loads(json.dumps(before))
    raw_before = get_trajectory(before)
    protected: list[dict[str, Any]] = []
    decisions: list[dict[str, Any]] = []
    persistent_constraints: dict[str, Any] = {}

    # step -> reasoning record
    reasoning_by_step = {record["step"]: record for record in kg_reasoning}

    for index, raw_step in enumerate(raw_before):
        candidate = apply_policy_patch(raw_step, persistent_constraints)

        # Evaluate current prefix exactly as an observed runtime trace.
        current_steps = normalize_runtime_trace({"trajectory": protected + [candidate]})
        current_results = check_ltl(current_steps, requirements)
        violated = [
            r["id"]
            for r in current_results
            if r["status"] == "VIOLATED"
            and index in r.get("violation_trigger_states", r["violating_states"])
        ]

        record: dict[str, Any] = {
            "step": index,
            "action": text(raw_step.get("action")),
            "violated_requirements": violated,
            "policies_in_force": sorted(persistent_constraints),
            "policy_evaluations": [],
            "technical_operations": [],
            "human_intervention": False,
        }
        for result in current_results:
            goal = next(
                (req.get("goal") for req in requirements if req["id"] == result["id"]),
                None,
            )
            record["policy_evaluations"].append({
                "requirement": result["id"],
                "goal": goal,
                "satisfaction": result["status"],
                "policy": "N/A" if result["status"] == "NOT_TRIGGERED" else action_policy(
                    result["status"].lower()
                ),
            })

        # Unknown due to insufficient governance evidence must not silently
        # become ALLOW. The paper's action policy maps UNKNOWN -> ESCALATE.
        reasoning = reasoning_by_step.get(index)
        if raw_step.get("action") and reasoning is None:
            record["decision"] = "ESCALATE"
            record["reason"] = "No normalized security signal / goal evidence."
            record["escalate_to_human"] = True
            record["human_intervention"] = True
            candidate["security_decision"] = {
                "decision": "ESCALATE",
                "reason": record["reason"],
            }
            protected.append(candidate)
            decisions.append(record)
            continue

        if reasoning is not None and reasoning.get("selected_leaf_goal") is None:
            record["decision"] = "ESCALATE"
            record["reason"] = "Insufficient evidence to select a relevant leaf goal."
            record["escalate_to_human"] = True
            record["human_intervention"] = True
            state = parse_json_object(candidate.get("state"))
            state["action_blocked"] = True
            state["mitigation_active"] = False
            candidate["state"] = json.dumps(state, ensure_ascii=False)
            candidate["original_observation"] = candidate.get("observation")
            candidate["observation"] = "[GRAIL] action escalated for human review"
            candidate["security_decision"] = {
                "decision": "ESCALATE",
                "reason": record["reason"],
            }
            protected.append(candidate)
            decisions.append(record)
            continue

        # No violated requirement -> satisfied/allowed path.
        if not violated:
            record["goal_policy_decisions"] = [
                {"requirement": r["id"], "policy": "ALLOW"}
                for r in current_results
                if r["status"] == "SATISFIED"
            ]
            record["decision"] = "ALLOW"
            protected.append(candidate)
            decisions.append(record)
            continue

        # Violated -> pi_g = BLOCK for every affected goal.
        record["decision"] = "BLOCK"
        record["goal_policy_decisions"] = [
            {"requirement": req_id, "policy": "BLOCK"}
            for req_id in violated
        ]

        applied_operations = []
        escalated = False
        mitigation_records = []
        operation_by_id: dict[str, dict[str, Any]] = {}

        # First resolve one candidate operation per violated requirement.
        for req_id in violated:
            reasoning = reasoning_by_step.get(index)
            bound_goal = next(
                (req.get("goal") for req in requirements if req["id"] == req_id),
                None,
            )
            operation = None

            if bound_goal and reasoning:
                for candidate_goal in reasoning.get("goal_candidates", []):
                    if candidate_goal.get("uri") == bound_goal.get("uri"):
                        operation = select_mitigation(
                            model,
                            candidate_goal.get("operations", []),
                            reasoning.get("runtime_fact", ""),
                            event_type=reasoning.get("event_type"),
                        )
                        break

            mitigation_records.append({
                "requirement": req_id,
                "goal": bound_goal,
                "operation": operation,
            })

            if isinstance(operation, dict):
                op_id = operation.get("operation_id") or operation.get("operation_name")
                if op_id:
                    operation_by_id.setdefault(op_id, operation)

        # Apply each unique technical operation once to the concrete action.
        for operation in operation_by_id.values():
            candidate, enforcement = apply_enforcement_adapter(candidate, operation)
            escalated = escalated or bool(enforcement.get("requires_human"))
            applied_operations.append(operation)

            record.setdefault("technical_operations", []).append({
                "operation_id": operation.get("operation_id"),
                "operation_name": operation.get("operation_name"),
                "source": operation.get("source"),
                "goal_operation_score": operation.get("goal_operation_score"),
                "selection_score": operation.get("selection_score"),
                "selection_reason": operation.get("selection_reason"),
                "enforcement_adapter": enforcement.get("adapter"),
            })

        if not applied_operations:
            escalated = True

        # Record the requirement-to-operation links once, including the same operation reused by multiple violated requirements.
        for mitigation in mitigation_records:
            operation = mitigation.get("operation")
            mitigation["enforcement"] = {
                "adapter": (operation or {}).get("enforcement_adapter") if isinstance(operation, dict) else None,
                "applied": bool(operation),
                "requires_human": escalated if not operation else False,
            }
        record["mitigations"] = mitigation_records

        # A successful adapter produces persistent security constraints.
        # These constraints represent the control now active in the runtime
        # environment, so later trajectory states cannot accidentally restore the pre-mitigation security facts.
        state_after = parse_json_object(candidate.get("state"))
        for key in (
            "path_validation",
            "authentication",
            "dependency_allowlist",
            "command_allowlist",
            "file_access_granted",
            "sensitive_data_exposed",
            "mitigation_active",
        ):
            if key in state_after:
                persistent_constraints[key] = state_after[key]

        # Verify the patched prefix. If it still violates a requirement, the
        # only honest result is ESCALATE rather than claiming compliance.
        patched_steps = normalize_runtime_trace({"trajectory": protected + [candidate]})
        patched_results = check_ltl(patched_steps, requirements)
        still = [
            r["id"]
            for r in patched_results
            if r["status"] == "VIOLATED" and index in r["violating_states"]
        ]

        if still:
            record["decision"] = "ESCALATE"
            record["human_intervention"] = True
            record["reason"] = (
                "Selected mitigation did not restore all violated requirements: "
                + ", ".join(still)
            )
            escalated = True
        elif escalated:
            # The policy is BLOCK, but mitigation approval itself needs a human.
            record["decision"] = "BLOCK"
            record["escalate_to_human"] = True
            record["human_intervention"] = True
            record["reason"] = "Mitigation requires human approval."
        else:
            record["decision"] = "BLOCK"
            record["reason"] = "Action blocked and mitigation applied."

        candidate["security_decision"] = {
            "decision": record["decision"],
            "violated_requirements": violated,
            "escalate_to_human": escalated,
            "mitigations": record.get("mitigations", []),
        }

        protected.append(candidate)
        decisions.append(record)

    after["trajectory"] = protected
    after.setdefault("info", {})["generated_by"] = "GRAIL security agent"
    after["grail_security_agent"] = {
        "decision_counts": dict(Counter(d["decision"] for d in decisions)),
        "final_constraints": persistent_constraints,
    }
    return after, decisions



def _model_ids(model_part: list[dict[str, Any]] | None) -> set[str]:
    return {
        str(item["id"])
        for item in (model_part or [])
        if isinstance(item, dict) and item.get("id")
    }


def load_adaptation_history(path: str | Path):
    """
    Load persistent self-adaptation history.

    The history stores cumulative violation counts across executions. It is
    intentionally kept separate from the .traj so that a protected trajectory
    does not erase the fact that a violation occurred in an earlier episode.
    """
    path = Path(path)
    if not path.exists():
        return {
            "violations_by_requirement": {},
            "unresolved_by_requirement": {},
        }

    with path.open("r", encoding="utf-8") as f:
        data = json.load(f)

    if not isinstance(data, dict):
        raise ValueError("Adaptation history must contain a JSON object")

    violations = data.get("violations_by_requirement", {})
    unresolved = data.get("unresolved_by_requirement", {})

    if not isinstance(violations, dict) or not isinstance(unresolved, dict):
        raise ValueError(
            "Adaptation history must contain object fields "
            "'violations_by_requirement' and 'unresolved_by_requirement'"
        )

    return {
        "violations_by_requirement": {
            str(k): int(v) for k, v in violations.items()
        },
        "unresolved_by_requirement": {
            str(k): int(v) for k, v in unresolved.items()
        },
    }


def save_adaptation_history(path: str | Path, history):
    """
    Persist the cumulative self-adaptation history as JSON.
    """
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as f:
        json.dump(history, f, indent=2, ensure_ascii=False)


def detect_environmental_changes(baseline_model, current_model):
    """
    Detect added/removed agents, tools, memories, or channels.

    The runtime model is S=<A,T,M,C> in this prototype. Environmental
    snapshots can be supplied explicitly through the CLI when the change is
    external to the observed trajectory.
    """
    changes: dict[str, dict[str, list[str]]] = {}
    baseline_model = baseline_model or {}
    current_model = current_model or {}

    for key in DEFAULT_ENVIRONMENT_CHANGE_KEYS:
        before = _model_ids(baseline_model.get("S", {}).get(key))
        after = _model_ids(current_model.get("S", {}).get(key))
        added = sorted(after - before)
        removed = sorted(before - after)
        if added or removed:
            changes[key] = {"added": added, "removed": removed}

    return {
        "triggered": bool(changes),
        "changes": changes,
        "action": (
            "ingest_governance_and_recompute_refinements"
            if changes else "none"
        ),
        "requires_human_approval": bool(changes),
    }


def detect_goal_conflicts(decisions, requirements, scenario):
    """
    Detect conflicts explicitly declared in the scenario profile.

    A trajectory alone does not encode stakeholder preferences. The scenario
    may therefore declare ``goal_conflicts`` with ``goal_ids``/``goal_uris``.
    """
    configured = scenario.get("goal_conflicts", []) or []
    if not configured:
        return {
            "triggered": False,
            "conflicts": [],
            "requires_human_approval": False,
        }

    violated_goal_ids = set()
    for decision in decisions:
        for req_id in decision.get("violated_requirements", []):
            req = next((r for r in requirements if r.get("id") == req_id), None)
            goal = req.get("goal") if req else None
            if isinstance(goal, dict):
                violated_goal_ids.add(goal.get("goal_id"))
                violated_goal_ids.add(goal.get("uri"))

    triggered = []
    for conflict in configured:
        identifiers = (
            set(conflict.get("goal_ids", []))
            | set(conflict.get("goal_uris", []))
        )
        matched = [value for value in identifiers if value in violated_goal_ids]
        if len(matched) >= 2 or (matched and conflict.get("force_check")):
            priority = conflict.get("priority")
            triggered.append({
                "matched_goals": matched,
                "priority": priority,
                "resolution": (
                    "prioritize_configured_goal"
                    if priority else "escalate_to_stakeholders"
                ),
            })

    return {
        "triggered": bool(triggered),
        "conflicts": triggered,
        "requires_human_approval": any(
            c["resolution"] != "prioritize_configured_goal"
            for c in triggered
        ),
    }


def _adaptation_targets_for_requirement(req_id, requirements, operations_by_req):
    """
    Return the requirement, bound goal, and concrete operations to review.
    """
    req = next((r for r in requirements if r.get("id") == req_id), None)
    goal = req.get("goal") if isinstance(req, dict) else None

    goals = []
    if isinstance(goal, dict):
        goals.append({
            "goal_id": goal.get("goal_id"),
            "goal_name": goal.get("goal_name"),
            "uri": goal.get("uri"),
        })

    operations = []
    seen = set()
    for operation in operations_by_req.get(req_id, []):
        if not isinstance(operation, dict):
            continue
        op_id = operation.get("operation_id") or operation.get("operation_name")
        if not op_id or op_id in seen:
            continue
        seen.add(op_id)
        operations.append({
            "operation_id": operation.get("operation_id"),
            "operation_name": operation.get("operation_name"),
        })

    return {
        "requirement": req_id,
        "goals": goals,
        "operations": operations,
    }


def build_self_adaptation_plan(
    decisions,
    before,
    after,
    scenario,
    adaptation_history_path: str | Path = DEFAULT_ADAPTATION_HISTORY,
    repeat_threshold: int = DEFAULT_REPEAT_THRESHOLD,
    environment_before=None,
    environment_after=None,
):
    """
    Implement the paper's three self-adaptation triggers.

    Persistent history is used for repeated violations across executions.
    The adaptation decision is triggered when a requirement crosses the
    configured threshold during the current execution.

    The function proposes an adaptation plan but does not mutate the persistent
    RDF goal model. Structural changes require human approval.
    """
    adaptation_cfg = scenario.get("self_adaptation", {}) or {}
    # Use the requirements BOUND to their leaf goals (beta(r)) when available,
    # so that adaptation targets and conflict detection can reference goals.
    # scenario["requirements"] does not carry the runtime goal binding.
    bound_requirements = (
        (before or {}).get("formal_requirements")
        or scenario.get("requirements", [])
    )
    repeat_threshold = max(
        1,
        int(
            adaptation_cfg.get(
                "repeat_violation_threshold",
                repeat_threshold,
            )
        ),
    )

    history = load_adaptation_history(adaptation_history_path)
    previous_violations = Counter(history["violations_by_requirement"])
    previous_unresolved = Counter(history["unresolved_by_requirement"])

    current_violations = Counter()
    current_unresolved = Counter()
    operations_by_req: dict[str, list[dict[str, Any]]] = defaultdict(list)

    for decision in decisions:
        for req_id in decision.get("violated_requirements", []):
            current_violations[req_id] += 1
            if decision.get("decision") == "ESCALATE":
                current_unresolved[req_id] += 1

        for mitigation in decision.get("mitigations", []):
            req_id = mitigation.get("requirement")
            operation = mitigation.get("operation")
            if req_id and isinstance(operation, dict):
                operations_by_req[req_id].append(operation)

    cumulative_violations = previous_violations + current_violations
    cumulative_unresolved = previous_unresolved + current_unresolved

    # Persist the updated history even when no adaptation is triggered.
    updated_history = {
        "violations_by_requirement": dict(sorted(cumulative_violations.items())),
        "unresolved_by_requirement": dict(sorted(cumulative_unresolved.items())),
    }
    save_adaptation_history(adaptation_history_path, updated_history)

    actions: list[dict[str, Any]] = []
    repeated_requirements = []

    # Threshold crossing, rather than "already above threshold", prevents the
    # same adaptation action from being re-proposed on every later clean run.
    for req_id, current_count in sorted(current_violations.items()):
        previous_count = previous_violations.get(req_id, 0)
        cumulative_count = cumulative_violations.get(req_id, 0)

        if previous_count >= repeat_threshold:
            continue
        if cumulative_count < repeat_threshold:
            continue

        repeated_requirements.append(req_id)
        ops = operations_by_req.get(req_id, [])
        low_risk = bool(ops) and all(
            mitigation_risk(op).get("risk_level") == "low"
            for op in ops
        )
        target = _adaptation_targets_for_requirement(
            req_id,
            bound_requirements,
            operations_by_req,
        )

        if current_unresolved.get(req_id, 0) > 0:
            actions.append({
                "trigger": "goal_violation",
                "type": "escalate_to_stakeholders",
                "reason": "Repeated unresolved violation pattern.",
                "adaptation_target": target,
                "automatable": False,
                "requires_human_approval": bool(
                    adaptation_cfg.get(
                        "structural_changes_require_human_approval",
                        True,
                    )
                ),
            })
        elif low_risk:
            actions.append({
                "trigger": "goal_violation",
                "type": "adjust_operationalization",
                "reason": (
                    "Repeated violations suggest the current "
                    "operationalization is ineffective or insufficient."
                ),
                "adaptation_target": target,
                "automatable": bool(
                    adaptation_cfg.get(
                        "parameter_adjustments_may_be_automated",
                        True,
                    )
                ),
                "requires_human_approval": not bool(
                    adaptation_cfg.get(
                        "parameter_adjustments_may_be_automated",
                        True,
                    )
                ),
            })
        else:
            actions.append({
                "trigger": "goal_violation",
                "type": "refine_goal_or_operationalization",
                "reason": "Repeated violations require governance-model review.",
                "adaptation_target": target,
                "automatable": False,
                "requires_human_approval": True,
            })

    conflict_state = detect_goal_conflicts(
        decisions,
        bound_requirements,
        scenario,
    )
    if conflict_state["triggered"]:
        actions.append({
            "trigger": "goal_conflict",
            "type": "resolve_goal_conflict",
            "details": conflict_state["conflicts"],
            "automatable": not conflict_state["requires_human_approval"],
            "requires_human_approval": conflict_state["requires_human_approval"],
        })

    baseline_model = (
        environment_before
        if environment_before is not None
        else before.get("formal_model", {})
    )
    current_model = (
        environment_after
        if environment_after is not None
        else after.get("formal_model", {})
    )
    environment_state = detect_environmental_changes(
        baseline_model,
        current_model,
    )
    if environment_state["triggered"]:
        actions.append({
            "trigger": "environmental_change",
            "type": "ingest_governance_and_recompute_refinements",
            "details": environment_state["changes"],
            "automatable": False,
            "requires_human_approval": True,
        })

    triggered = bool(actions)
    structural = any(
        a["type"] in {
            "refine_goal_or_operationalization",
            "resolve_goal_conflict",
            "ingest_governance_and_recompute_refinements",
            "escalate_to_stakeholders",
        }
        for a in actions
    )

    return {
        "status": "TRIGGERED" if triggered else "NOT_TRIGGERED",
        "configuration": {
            "repeat_violation_threshold": repeat_threshold,
            "structural_changes_require_human_approval": bool(
                adaptation_cfg.get(
                    "structural_changes_require_human_approval",
                    True,
                )
            ),
            "parameter_adjustments_may_be_automated": bool(
                adaptation_cfg.get(
                    "parameter_adjustments_may_be_automated",
                    True,
                )
            ),
        },
        "history": {
            "path": str(Path(adaptation_history_path)),
            "previous_violations_by_requirement": dict(
                sorted(previous_violations.items())
            ),
            "current_violations_by_requirement": dict(
                sorted(current_violations.items())
            ),
            "cumulative_violations_by_requirement": dict(
                sorted(cumulative_violations.items())
            ),
        },
        "monitoring_window": {
            "repeat_threshold": repeat_threshold,
            "violations_by_requirement": dict(
                sorted(current_violations.items())
            ),
            "unresolved_by_requirement": dict(
                sorted(current_unresolved.items())
            ),
        },
        "triggers": {
            "goal_violations": bool(repeated_requirements),
            "goal_conflicts": conflict_state["triggered"],
            "environmental_changes": environment_state["triggered"],
        },
        "environmental_changes": environment_state,
        "actions": actions,
        "goal_model_update": {
            "triggered": triggered,
            "structural_change_proposed": structural,
            "requires_human_approval": any(
                a.get("requires_human_approval") for a in actions
            ),
            "applied_automatically": any(
                a.get("automatable") for a in actions
            ),
            "note": (
                "The prototype does not persistently mutate the RDF goal model. "
                "Structural changes are proposed for human approval; safe runtime "
                "parameter adjustments may be automated."
            ),
        },
    }


# 10) ----------- End-to-end analysis -----------

def analyze_runtime_trace(
    traj_path,
    kg_path,
    model,
    store,
    leaf_goals,
    leaf_goal_embeddings,
    scenario,
    top_k_goals,
    operation_limit,
    operation_score_threshold,
    bound_requirements_override: list[dict[str, Any]] | None = None,
):
    """
    Run Monitor -> Evaluate -> Trace preparation for one trajectory.
    """
    traj = load_traj(traj_path)
    steps = normalize_runtime_trace(traj, scenario=scenario)
    system_model = build_agentic_system_model(traj, steps, scenario)

    runtime_goal_reasoning = []
    for step in steps:
        if not step.get("event_type"):
            continue
        runtime_goal_reasoning.append(
            analyze_step_against_kg(
                model=model,
                store=store,
                leaf_goals=leaf_goals,
                leaf_goal_embeddings=leaf_goal_embeddings,
                step=step,
                top_k_goals=top_k_goals,
                operation_limit=operation_limit,
                operation_score_threshold=operation_score_threshold,
            )
        )

    requirements = [dict(req) for req in scenario.get("requirements", [])]
    if bound_requirements_override is None:
        bound_requirements = bind_requirements_to_goals(
            requirements, runtime_goal_reasoning
        )
        goal_binding_source = "current_runtime_reasoning"
    else:
        # Governance episodes keep the requirement -> goal binding stable during re-verification.
        # A changed runtime embedding alone is not treated as a goal-model adaptation event.
        bound_requirements = [dict(req) for req in bound_requirements_override]
        goal_binding_source = "before_runtime_reasoning_stable_binding"

    ltl_results = check_ltl(steps, bound_requirements)
    goal_states = goal_satisfaction_states(bound_requirements, ltl_results)

    violations = []
    reasoning_by_step = {r["step"]: r for r in runtime_goal_reasoning}

    for result in ltl_results:
        if result["status"] != "VIOLATED":
            continue
        goal = next(
            (r.get("goal") for r in bound_requirements if r["id"] == result["id"]),
            None,
        )
        violations.append({
            "requirement_id": result["id"],
            "formula": result["formula"],
            "goal": goal,
            "steps": [
                {
                    "step": step_id,
                    "event_type": steps[step_id].get("event_type"),
                    "runtime_fact": reasoning_by_step.get(step_id, {}).get("runtime_fact"),
                    "bound_goal": goal,
                    "selected_leaf_goal": reasoning_by_step.get(step_id, {}).get("selected_leaf_goal"),
                    "selected_mitigation": reasoning_by_step.get(step_id, {}).get("selected_mitigation"),
                }
                for step_id in result.get(
                    "violation_trigger_states", result["violating_states"]
                )
            ],
        })

    return {
        "trajectory": {
            "path": str(Path(traj_path).resolve()),
            "name": traj.get("name"),
            "environment": traj.get("environment"),
            "info": traj.get("info"),
        },
        "formal_model": system_model,
        "steps": [
            {
                "step": s["step"],
                "signal": s["signal"],
                "event_type": s["event_type"],
                "classified": s["classified"],
                "facts": sorted(k for k, v in s["facts"].items() if v is True),
            }
            for s in steps
        ],
        "runtime_goal_reasoning": runtime_goal_reasoning,
        "formal_requirements": bound_requirements,
        "goal_binding_source": goal_binding_source,
        "ltl_results": ltl_results,
        "goal_satisfaction": goal_states,
        "violations": violations,
        "knowledge_graph": {
            "path": str(Path(kg_path).resolve()),
            "leaf_goal_count": len(leaf_goals),
        },
    }


def compare_before_after(before, after):
    """
    Compare requirement verdicts before and after enforcement.
    """
    before_status = {r["id"]: r["status"] for r in before["ltl_results"]}
    after_status = {r["id"]: r["status"] for r in after["ltl_results"]}
    ids = sorted(set(before_status) | set(after_status))
    comparison = [
        {
            "requirement_id": req_id,
            "before": before_status.get(req_id),
            "after": after_status.get(req_id),
            "changed": before_status.get(req_id) != after_status.get(req_id),
        }
        for req_id in ids
    ]
    before_violations = sum(r["status"] == "VIOLATED" for r in before["ltl_results"])
    after_violations = sum(r["status"] == "VIOLATED" for r in after["ltl_results"])
    return {
        "ltl_comparison": comparison,
        "before_violation_count": before_violations,
        "after_violation_count": after_violations,
        "security_recovery_success": before_violations > 0 and after_violations == 0,
        "self_adaptation_triggered": False,
    }


