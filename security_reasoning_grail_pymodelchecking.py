# 2. ----------- Runtime signal normalization -- Sigma -----------

def infer_event_type(action, observation, state):
    """
    Infer the event type from the concrete action first.

    The real SWE-agent trajectory contains both:
      - a malicious HTTP request containing ``../``; and
      - a later Python command that *also* contains ``../`` while analysing
        the vulnerability.

    Therefore ``../`` alone must not determine the event type.
    We classify concrete tool/action forms first, then use the generic path-traversal heuristic as a fallback.
    """
    explicit = (
        state.get("event_type")
        or state.get("eventType")
        or state.get("security_event")
        or state.get("securityEvent")
        or state.get("event")
    )
    if isinstance(explicit, str) and explicit.strip():
        return explicit.strip()

    action_l = action.lower()
    haystack = f"{action}\n{observation}\n{text(state)}".lower()

    # A curl/wget request carrying ../ in its URL is the actual path-traversal
    # attack in this case study.
    if re.search(r"\b(curl|wget)\b", action_l) and any(token in haystack for token in (
        "../", "..\\", "%2e%2e", "path traversal", "parent-directory"
    )):
        return "path_traversal"

    # Dependency installation.
    if re.search(r"\b(pip|pip3)\s+install\b|\bnpm\s+install\b|\bpoetry\s+add\b", haystack):
        return "install_dependency"

    if any(token in haystack for token in ("chmod ", "chown ", "setfacl ")):
        return "permission_change"

    if any(token in haystack for token in (
        "apply_patch", "sed -i", "modify source", "patch source"
    )):
        return "modify_source"

    # Shell/program execution gets classified before the generic ../ fallback.
    if re.search(r"\b(python|python3|bash|sh)\b", action_l):
        return "execute_command"

    if re.search(r"\b(curl|wget)\b", action_l) and "http" in haystack:
        return "external_network_access"

    if re.search(r"(^|\s)(cat|head|tail|less|more|sed|grep|rg)\s+", action_l):
        return "read_file"

    if any(token in haystack for token in (
        "../", "..\\", "%2e%2e", "path traversal", "parent-directory"
    )):
        return "path_traversal"

    return None


def infer_facts(action, observation, state, event_type: str | None):
    """
    Derive structured runtime security facts from one interaction signal.
    """
    facts: dict[str, bool] = {}

    # Explicit booleans supplied by telemetry have priority over heuristics.
    for raw_name, raw_value in state.items():
        if isinstance(raw_value, bool):
            facts[normalize_boolean_key(str(raw_name))] = raw_value

    haystack = f"{action}\n{observation}\n{text(state)}".lower()

    if event_type == "path_traversal":
        facts.setdefault("pathTraversalDetected", True)
        facts.setdefault("fileAccessAttempt", True)
        facts.setdefault("threatDetected", True)

    elif event_type == "install_dependency":
        facts.setdefault("installDependency", True)
        untrusted_markers = (
            "--index-url http://",
            "--extra-index-url http://",
            "--trusted-host",
            "git+http://",
            "git+git://",
            "--no-verify",
            "--insecure",
        )
        if any(marker in haystack for marker in untrusted_markers):
            facts.setdefault("untrustedSource", True)
            facts.setdefault("dependencyVulnerable", True)
            facts.setdefault("threatDetected", True)
        if any(marker in haystack for marker in (
            "cve-", "ghsa-", "known vulnerability", "vulnerable version"
        )):
            facts.setdefault("dependencyVulnerable", True)
            facts.setdefault("threatDetected", True)

    elif event_type == "read_file":
        facts.setdefault("fileAccessAttempt", True)

    elif event_type == "execute_command":
        facts.setdefault("commandExecuted", True)
        authorized_commands = (
            "pytest", "python -m pytest", "python -m unittest", "python -c ",
            "python3 -c ", "python - <<", "python3 - <<",
            "tox", "make ", "npm test", "npm run",
            "git ", "ls ", "cat ", "grep ",
        )
        # Treat normal inspection/test commands as authorized. Do not flag a
        # command merely because its argument mentions /tmp: our case-study
        # trajectory deliberately contains a safe Path.resolve() inspection of
        # /tmp/sensitive.traj.
        dangerous_command_markers = (
            "| bash", "| sh", "curl |bash", "curl | sh",
            "wget |bash", "wget | sh", "rm -rf /", "sudo ",
        )
        is_safe_command = any(tool in haystack for tool in authorized_commands)
        is_dangerous_command = any(marker in haystack for marker in dangerous_command_markers)
        if is_safe_command and not is_dangerous_command:
            facts.setdefault("commandAuthorized", True)
        else:
            facts.setdefault("threatDetected", True)

    elif event_type == "external_network_access":
        facts.setdefault("externalNetworkAccess", True)

    elif event_type == "permission_change":
        facts.setdefault("permissionChange", True)

    elif event_type == "modify_source":
        facts.setdefault("modifySource", True)

    if re.search(r"\b403\b|\bforbidden\b|\bblocked\b|\bdenied\b", haystack):
        facts.setdefault("actionBlocked", True)

    if any(marker in haystack for marker in (
        "x-security-agent: blocked",
        "mitigation active",
        "mitigation activated",
        "security-action: block",
        "x-grail: blocked",
    )):
        facts.setdefault("mitigationActive", True)

    if "threat detected" in haystack or "vulnerability detected" in haystack:
        facts.setdefault("threatDetected", True)

    if "sensitive data exposed" in haystack or "secret exposed" in haystack:
        facts.setdefault("sensitiveDataExposed", True)

    if event_type == "path_traversal" and re.search(r"\b200\s+ok\b", haystack):
        facts.setdefault("fileAccessGranted", True)

    if event_type == "path_traversal":
        if state.get("authentication") is False or state.get("authenticated") is False:
            facts.setdefault("unauthenticated", True)
        if state.get("remote_access") is True:
            facts.setdefault("remoteRequest", True)

    if facts.get("unauthenticated") and (
        facts.get("pathTraversalDetected") or facts.get("fileAccessAttempt")
    ):
        facts.setdefault("unauthorizedAccessAttempt", True)

    if facts.get("actionBlocked") and facts.get("fileAccessGranted") is not True:
        facts.setdefault("fileAccessGranted", False)

    if facts.get("pathTraversalDetected") and facts.get("fileAccessGranted"):
        facts.setdefault("sensitiveDataExposed", True)

    return facts


def signal_from_step(index, step):
    """
    Build a canonical Sigma interaction signal.

    Example:
        ActionProposal(
            agent="a_SWE",
            tool="path_traversal",
            parameters={...}
        )
    """
    event_type = step.get("event_type")
    state = step.get("state") or {}

    # The SWE-agent .traj adapter currently represents the principal runtime
    # action as ActionProposal. Additional signal types can be added here
    # without changing the GRAIL reasoning layer.
    signal_type = "ActionProposal" if step.get("action") else "Observation"

    return {
        "id": f"sigma_{index}",
        "index": index,
        "type": signal_type,
        "agent": state.get("agent", "a_SWE"),
        "tool": state.get("tool") or event_type,
        "parameters": {
            "action": step.get("action", ""),
            "path": state.get("requested_path"),
            "event_type": event_type,
        },
        "observation": step.get("observation", ""),
        "facts": dict(step.get("facts") or {}),
    }


def normalize_runtime_trace(traj, scenario: dict[str, Any] | None = None):
    """
    Normalize the raw .traj into Sigma + runtime security facts.
    """
    scenario = scenario or {}
    assumptions = dict(DEFAULT_RUNTIME_ASSUMPTIONS)
    assumptions.update(scenario.get("runtime_assumptions", {}) or {})

    normalized: list[dict[str, Any]] = []

    for index, raw_step in enumerate(get_trajectory(traj)):
        action = text(raw_step.get("action")).strip()
        observation = text(raw_step.get("observation")).strip()
        state = parse_json_object(raw_step.get("state"))

        event_type = infer_event_type(action, observation, state)

        # The real case-study trace does not explicitly record authentication
        # on the HTTP requests. Make the case-study assumption explicit in the
        # normalized runtime context rather than guessing it inside infer_facts.
        if event_type in {"path_traversal", "external_network_access"}:
            action_l = action.lower()
            is_http_request = bool(re.search(r"\b(curl|wget)\b.*https?://", action_l))
            if is_http_request:
                state.setdefault("remote_access", True)
                if assumptions.get("remote_http_requests_unauthenticated", False):
                    state.setdefault("authentication", False)

        facts = infer_facts(action, observation, state, event_type)

        step = {
            "time": index,
            "step": index,
            "action": action,
            "observation": observation,
            "response": text(raw_step.get("response")),
            "thought": text(raw_step.get("thought")),
            "state": state,
            "event_type": event_type,
            "facts": facts,
            "classified": bool(event_type) and any(facts.values()),
        }
        step["signal"] = signal_from_step(index, step)
        normalized.append(step)

    return normalized


# 3) ----------- Formal agentic-system model: S = <A,T,M,C> -----------

def build_agentic_system_model(traj, steps, scenario):
    """
    Instantiate the paper's S=<A,T,M,C> representation from the trace.

    C is intentionally scenario-dependent and may be empty.

    Example for this case study:
        S["C"] == []

    Example for a multi-agent scenario:
        S["C"] = [
            {
                "source": "a_SWE",
                "target": "a_security",
                "type": "runtime-policy-query",
            }
        ]
    """
    action_tools = sorted({
        str(step["signal"].get("tool"))
        for step in steps
        if step["signal"].get("tool")
    })

    memory_stores = sorted({
        str(step["state"].get("memory_store"))
        for step in steps
        if step["state"].get("memory_store")
    })
    if not memory_stores:
        memory_stores = ["trajectory_history"]

    # C is scenario-dependent. Do not invent channels merely because
    # components exist. Use only channels explicitly declared by the scenario.
    channels = list(scenario.get("communication_channels", []))

    system = {
        "A": [
            {"id": "a_SWE", "role": "functional_agent"},
            {"id": "a_security", "role": "security_agent"},
        ],
        "T": [
            {"id": tool, "permission_model": "scenario-defined"}
            for tool in action_tools
        ],
        "M": [
            {"id": memory, "read_write": "runtime-derived"}
            for memory in memory_stores
        ],
        "C": channels,
    }

    # Sigma is the paper's runtime signal stream.
    sigma = [step["signal"] for step in steps]

    return {
        "S": system,
        "Sigma": sigma,
        "scenario": scenario.get("name", "unnamed"),
    }


